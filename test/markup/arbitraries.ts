/**
 * fast-check generators of markup-ish text: tags (valid, unknown, malformed), escapes,
 * brackets, links, tildes, carets, line breaks and arbitrary characters.
 */

import fc from 'fast-check';

const PIECES = [
  '[b]',
  '[/b]',
  '[i]',
  '[/i]',
  '[u]',
  '[/u]',
  '[c]',
  '[c red]',
  '[c Bad]',
  '[/c]',
  '[m]',
  '[m1]',
  '[m2]',
  '[/m]',
  '[/m2]',
  '[*]',
  '[/*]',
  '[p]',
  '[/p]',
  "[']",
  "[/']",
  '[t]',
  '[/t]',
  '[s]',
  '[/s]',
  '[video]',
  '[/video]',
  '[preview]',
  '[/preview]',
  '[ref]',
  '[ref dict="d"]',
  '[/ref]',
  '[url]',
  '[/url]',
  '[lang id=1033]',
  '[lang name="English"]',
  '[lang]',
  '[lang id=x y]',
  '[/lang]',
  '[br]',
  '[/br]',
  '[ex]',
  '[/ex]',
  '[trn]',
  '[/trn]',
  '[!trs]',
  '[/!trs]',
  '[foo]',
  '[/foo]',
  '[B]',
  '[/B]',
  '[b x]',
  '[/b y]',
  '[]',
  '[/]',
  '[ b]',
  '[',
  ']',
  '[[',
  ']]',
  '\\',
  '\\[',
  '\\]',
  '\\ ',
  '\\\\',
  '<<',
  '>>',
  '<',
  '>',
  '~',
  '^',
  '^~',
  '\n',
  ' ',
  '\t',
  '@',
  '{',
  '}',
  'word',
  'Ж',
  '𝄞',
  String.fromCharCode(0xa0),
];

/** Text built from markup pieces and arbitrary characters. */
export const markupText = fc
  .array(
    fc.oneof(
      { weight: 6, arbitrary: fc.constantFrom(...PIECES) },
      { weight: 1, arbitrary: fc.string({ unit: 'binary', maxLength: 4 }) },
    ),
    { maxLength: 60 },
  )
  .map((parts) => parts.join(''));
